// Deterministic topic relevance; no visitor data is transmitted or persisted.
export function rankReading(weights={}) {
  const entries=Object.entries(weights).filter(([,v])=>Number.isFinite(v)&&v>0);
  const magnitude=Math.hypot(...entries.map(([,v])=>v));
  const ranked=CHAPTER_READINGS.map((reading,index)=>{
    const dot=entries.reduce((sum,[tag,value])=>sum+value*(reading.profile[tag]||0),0);
    const length=Math.hypot(...Object.values(reading.profile));
    const score=magnitude&&length?dot/magnitude/length:0;
    const matchedThemes=entries.filter(([tag])=>reading.profile[tag]).sort((a,b)=>b[1]*reading.profile[b[0]]-a[1]*reading.profile[a[0]]).map(([tag])=>tag);
    return {reading,score,matchedThemes,index};
  }).sort((a,b)=>b.score-a.score||a.index-b.index);
  return ranked[0]?.score>0?ranked[0]:null;
}
